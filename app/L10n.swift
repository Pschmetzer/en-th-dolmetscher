import Foundation

enum UILang: String, CaseIterable, Identifiable {
    case th, en, de
    var id: String { rawValue }
    var label: String { ["th": "🇹🇭 ไทย", "en": "🇬🇧 English", "de": "🇩🇪 Deutsch"][rawValue]! }
}

enum L {
    static let key = "uiLang"

    /// Standardsprache beim ersten Start: Systemsprache (de/en/th), sonst Englisch.
    static var defaultCode: String {
        for tag in Locale.preferredLanguages {
            let code = String(tag.prefix(2)).lowercased()
            if UILang(rawValue: code) != nil { return code }
        }
        return "en"
    }

    /// Gecachte Sprache – t() liest nicht bei jedem Aufruf aus UserDefaults.
    nonisolated(unsafe) private static var cached: UILang = .en
    nonisolated(unsafe) private static var started = false
    static var lang: UILang { start(); return cached }

    private static func start() {
        guard !started else { return }
        started = true
        let ud = UserDefaults.standard
        if ud.string(forKey: key) == nil { ud.set(defaultCode, forKey: key) }   // @AppStorage und L sind so immer einig
        cached = UILang(rawValue: ud.string(forKey: key) ?? "") ?? UILang(rawValue: defaultCode) ?? .en
        // Nr. 380: auf dem Haupt-Thread (kein Datenrennen um `cached`); sync() tut nur bei geänderter Sprache etwas
        NotificationCenter.default.addObserver(forName: UserDefaults.didChangeNotification, object: nil, queue: .main) { _ in
            let code = UserDefaults.standard.string(forKey: key) ?? ""
            if code != cached.rawValue { sync(code) }
        }
    }

    /// Cache sofort auf `code` setzen (Ansichten rufen das mit ihrem @AppStorage-Wert auf, bevor sie L.t nutzen).
    @discardableResult
    static func sync(_ code: String) -> Bool {
        start()
        guard let l = UILang(rawValue: code), l != cached else { return false }
        cached = l
        return true
    }

    /// Text in der gewählten Oberflächensprache (oder einer erzwungenen, z. B. Thai im Profil-Assistenten).
    static func t(_ key: String, _ forced: UILang? = nil) -> String {
        let l = forced ?? lang
        guard let row = table[key] else { return key }
        return row[l.rawValue] ?? row["en"] ?? key
    }

    /// Text mit Platzhaltern (%@, %d, %.1f) – Format aus der Tabelle.
    /// Nr. 41: Text für das aktive Sprachpaar. Standardpaar en/th: der feste Text; sonst der Text `<key>_pair`
    /// mit den Sprachnamen als Platzhalter (`names`, Standard: meine Sprache und Partnersprache).
    static func tp(_ key: String, _ names: [String]? = nil) -> String {
        if Langs.isDefaultPair { return t(key) }
        let n = names ?? [Langs.name(Langs.mine), Langs.name(Langs.partner)]
        return String(format: t(key + "_pair"), locale: Locale(identifier: lang == .de ? "de_DE" : "en_US"),
                      arguments: n as [CVarArg])
    }
    /// „Das war ich/Partner (Sprache)“ für das Kontextmenü der Blase.
    static func reassign(_ role: String) -> String {
        let me = Langs.meLang
        return tp(role == "me" ? "reassign_me" : "reassign_other",
                  [Langs.name(role == "me" ? me : Langs.target(me))])
    }

    static func f(_ key: String, _ args: CVarArg...) -> String {
        String(format: t(key), locale: Locale(identifier: lang == .de ? "de_DE" : "en_US"), arguments: args)
    }

